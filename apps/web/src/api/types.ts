/** GET /api/v1/system. Every section is optional; the UI renders only what is present. */
export interface SystemInfo {
  gateway?: GatewayInfo | null;
  storage?: { database?: StorageUsage; private?: StorageUsage; artifacts?: StorageUsage } | null;
  release?: ReleaseInfo | null;
  update?: UpdateStatus | null;
  feedback?: FeedbackStats | null;
}
