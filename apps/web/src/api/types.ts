/**
 * Wire types for the Gateway public API (/api/v1). They follow
 * contracts/openapi.yaml and schemas/feedback.schema.json, extended with the
 * Gateway/Runtime/Feedback fields agreed between the module owners. Fields the
 * Gateway may not send are optional: the UI shows "unknown" for them, it never
 * invents a value.
 */

export type Role = 'viewer' | 'human' | 'agent' | 'admin';

export interface Actor {
  id: string;
  role: Role;
  workspaceId: string;
}

export interface SessionInfo {
  actor: Actor;
  csrfToken: string;
  /** True for automatic same-origin local access without token pairing. */
  localAccess?: boolean;
}

export type ControlState =
  | 'IDLE'
  | 'HUMAN'
  | 'AGENT'
  | 'HANDOFF_PENDING'
  | 'CAPTURE'
  | 'MAINTENANCE'
  | 'ERROR_LOCKED';

export type LeaseMode = 'HUMAN' | 'AGENT';

export interface Lease {
  leaseId: string;
  workspaceId: string;
  holderId: string;
  mode: LeaseMode;
  epoch: number;
  runtimeGeneration: string;
  expiresAt: string;
}

/** Gateway lease grant. The capability token is deliberately not modelled: the UI never stores it. */
export interface LeaseGrant {
  lease: Lease;
}

export interface BrowserDestination {
  id: string;
  name: string;
  workspaceId: string;
  origin: string;
  current: boolean;
}

export interface Workspace {
  id: string;
  runtimeGeneration: string;
  controlState: ControlState;
  holderId: string | null;
  ready: boolean;
  // Optional runtime extensions (absent until the Gateway forwards them).
  epoch?: number | null | undefined;
  holderMode?: LeaseMode | null | undefined;
  lease?: Lease | null | undefined;
  leaseExpiresAt?: string | null | undefined;
  browserVersion?: string | undefined;
  display?: { width: number; height: number } | undefined;
  locked?: boolean | undefined;
  lockCode?: string | undefined;
  maintenance?: boolean | undefined;
  capture?: boolean | undefined;
  handoff?: Handoff | null | undefined;
  resources?: WorkspaceResources | null | undefined;
  /** Usage mode and pause. Absent or unparseable policy MUST be treated as unknown (fail closed), never as AGENT. */
  agentControl?: AgentControl | undefined;
}

export type AgentMode = 'NOVNC' | 'AGENT';

/** Authoritative usage mode, kept separate from `controlState`. `revision` increases on every policy change. */
export interface AgentControl {
  mode: AgentMode;
  paused: boolean;
  revision: number;
  /** RFC 3339 timestamp. */
  updatedAt: string;
}

/** GET /workspaces/{id}/agent/setup: English onboarding prompt generated by the Gateway (never contains secrets). */
export interface AgentSetup {
  prompt: string;
}

export type HandoffStatus = 'DRAINING' | 'READY' | 'DRAIN_TIMEOUT';

export interface Handoff {
  requestId: string;
  status: HandoffStatus;
  drained: boolean;
  forced: boolean;
  uncertainEffects?: boolean | undefined;
  priorLease: { leaseId: string; holderId: string; mode: LeaseMode } | null;
  expiresAt: string;
}

export interface TakeoverPending {
  status: 'HANDOFF_PENDING';
  requestId: string;
}

export interface BrowserTarget {
  id: string;
  type: string;
  title: string;
  url: string;
  visible: boolean | null;
}

export interface TargetsResponse {
  targets: BrowserTarget[];
}

/** Raw runtime readiness detail proxied by GET /workspaces/{ws}/health. */
export interface RuntimeHealth {
  ready: boolean;
  workspace?: unknown;
  locked?: boolean;
  lockCode?: string;
  lease?: unknown;
  detail?: unknown;
}

export type FileArea = 'downloads' | 'uploads';

export interface ResourceDisk {
  name: 'profile' | 'downloads';
  totalBytes: number;
  availableBytes: number | null;
}

/** Sampled runtime resource counters. `null` means unknown, never zero. */
export interface WorkspaceResources {
  sampledAt: string;
  cpu: { usageNanos: number | null; cores: number | null };
  memory: { currentBytes: number | null; maxBytes: number | null };
  disk: ResourceDisk[];
}

export type LatencyStat = { count: number; avgMs: number; maxMs: number };

/** Delivery and capture counters reported by the feedback store (/system.feedback). */
export interface FeedbackStats {
  queueDepth: number;
  deliveries: Record<'READY' | 'QUEUED' | 'ACKNOWLEDGED' | 'IN_PROGRESS' | 'RESOLVED' | 'VERIFIED' | 'CANCELLED', number>;
  openDrafts: number;
  captures: Record<'awaitingUpload' | 'capturing' | 'ready' | 'failed', number>;
  privateBytes: number;
  sharedBytes: number;
  /** Configured optional limits; 0 means no limit. */
  limits: { maxDrafts: number; maxOpenCaptures: number; maxPrivateBytes: number; maxSharedBytes: number };
  desktopCaptureLatency: LatencyStat;
  ackLatency: LatencyStat;
  artifactFailures: number;
  events: number;
}

export interface ScreenSize {
  width: number;
  height: number;
}

/** `supported` is an explicit allowlist; one entry (the current size) means resizing is unavailable. */
export interface ResolutionInfo {
  current: ScreenSize;
  supported: ScreenSize[];
}

export interface FileEntry {
  name: string;
  size: number;
  modifiedAt: string;
}

export interface FileUsage {
  usedBytes: number;
  /** 0 means no storage quota is configured. */
  quotaBytes: number;
  fileCount: number;
  /** 0 means no file-count limit is configured. */
  maxFiles: number;
}

export interface FileListing {
  area: FileArea;
  files: FileEntry[];
  usage: FileUsage;
}

// ---------------------------------------------------------------- captures

export type CaptureSource = 'desktop' | 'page-viewport' | 'page-full' | 'drawing';
export type CaptureProvenance = 'client-framebuffer' | 'runtime-cdp' | 'generated-canvas';
export type CaptureStatus = 'awaiting-upload' | 'capturing' | 'ready' | 'failed';
export type Consistency = 'stable-navigation' | 'best-effort' | 'unknown';

export interface PageInfo {
  urlSanitized: string;
  titleSanitized: string;
  viewportWidthCss: number;
  viewportHeightCss: number;
  pixelsPerCssX: number;
  pixelsPerCssY: number;
  scrollXCss: number;
  scrollYCss: number;
  browserVersion: string;
}

export interface CaptureState {
  captureId: string;
  workspaceId: string;
  status: CaptureStatus;
  consistency: Consistency;
  source?: CaptureSource | undefined;
  provenance?: CaptureProvenance | undefined;
  imageWidthPx?: number | undefined;
  imageHeightPx?: number | undefined;
  capturedAt?: string | undefined;
  serverReceivedAt?: string | undefined;
  /** Empty string for drawings: a generated canvas has no runtime generation. */
  runtimeGeneration?: string | undefined;
  targetId?: string | null | undefined;
  navigationId?: string | null | undefined;
  page?: PageInfo | undefined;
  /** Present on crops: how this capture derives from its parent. Shape owned by the feedback module. */
  parentTransform?: Record<string, unknown> | undefined;
  expiresAt?: string | undefined;
  feedbackId?: string | undefined;
}

/** Page captures use a target and lease; desktops are uploaded by the viewer, and drawings are generated from pixel dimensions only. */
export type CreateCaptureRequest =
  | { source: 'desktop' | 'page-viewport'; targetId?: string; leaseId?: string; allowInterrupt?: boolean }
  | { source: 'drawing'; imageWidthPx: number; imageHeightPx: number };

export interface CropRequest {
  x: number;
  y: number;
  width: number;
  height: number;
}

// ---------------------------------------------------------------- feedback

export type FeedbackKind = 'bug' | 'task' | 'question' | 'visual-regression';
export type FeedbackIntent = 'analyze-only' | 'reproduce' | 'modify-and-verify';

export interface TaskFields {
  kind: FeedbackKind;
  intent: FeedbackIntent;
  title: string;
  description: string;
  expectedResult: string;
  actualResult: string;
  reproductionSteps: string[];
}

export interface Point {
  x: number;
  y: number;
}

export interface NormRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export type ArrowStyle = 'filled' | 'open' | 'double' | 'curved';
export type TextStyle = 'plain' | 'outline' | 'label' | 'shadow' | 'mono' | 'bold' | 'underline';

export interface AnnotationStyle {
  stroke?: string;
  /** Optional `#RRGGBB` shape fill; absent means transparent. */
  fill?: string;
  strokeWidthPx?: number;
  fontSizePx?: number;
  /** Highlight only: fill alpha 0.1..0.8 (default 0.35). Schema 0.3. */
  opacity?: number;
  /** Blur/pixelate only: integer radius/block edge in source pixels, 2..64. Schema 0.3. */
  effectSizePx?: number;
  /** Arrow only; absent means the original filled head. Schema 0.3. */
  arrowStyle?: ArrowStyle;
  /** Text only; absent means the original outline. Schema 0.3. */
  textStyle?: TextStyle;
  /** Freehand only; absent means false (legacy polyline). Schema 0.3. */
  smoothing?: boolean;
}

interface AnnotationBase {
  id: string;
  comment?: string;
  style?: AnnotationStyle;
}

export interface RectangleAnnotation extends AnnotationBase {
  kind: 'rectangle';
  geometry: NormRect;
}
export interface EllipseAnnotation extends AnnotationBase {
  kind: 'ellipse';
  geometry: NormRect;
}
export interface DiamondAnnotation extends AnnotationBase {
  kind: 'diamond';
  geometry: NormRect;
}
export interface LineAnnotation extends AnnotationBase {
  kind: 'line';
  geometry: { start: Point; end: Point };
}
export interface ArrowGeometry {
  start: Point;
  end: Point;
  /** Quadratic curve control for `arrowStyle: 'curved'`. Schema 0.3. */
  control?: Point;
}
export interface ArrowAnnotation extends AnnotationBase {
  kind: 'arrow';
  geometry: ArrowGeometry;
}
export interface FreehandAnnotation extends AnnotationBase {
  kind: 'freehand';
  geometry: { points: Point[] };
}
export interface TextAnnotation extends AnnotationBase {
  kind: 'text';
  geometry: { position: Point; text: string };
}
export interface PinAnnotation extends AnnotationBase {
  kind: 'pin';
  geometry: { position: Point; number: number };
}
/** Base-image effects. They are cosmetic: blur and pixelate are NOT secure redaction. */
export interface HighlightAnnotation extends AnnotationBase {
  kind: 'highlight';
  geometry: NormRect;
}
export interface SpotlightAnnotation extends AnnotationBase {
  kind: 'spotlight';
  geometry: NormRect;
}
export interface BlurAnnotation extends AnnotationBase {
  kind: 'blur';
  geometry: NormRect;
}
export interface PixelateAnnotation extends AnnotationBase {
  kind: 'pixelate';
  geometry: NormRect;
}
export interface RedactAnnotation extends AnnotationBase {
  kind: 'redact';
  geometry: NormRect;
  mode: 'solid';
}

export type Annotation =
  | RectangleAnnotation
  | EllipseAnnotation
  | DiamondAnnotation
  | ArrowAnnotation
  | LineAnnotation
  | FreehandAnnotation
  | TextAnnotation
  | PinAnnotation
  | RedactAnnotation
  | HighlightAnnotation
  | SpotlightAnnotation
  | BlurAnnotation
  | PixelateAnnotation;

export type AnnotationKind = Annotation['kind'];

