export type UpdatePhase =
  | 'not-configured'
  | 'idle'
  | 'candidate-available'
  | 'awaiting-approval'
  | 'applying'
  | 'rolling-back'
  | 'failed-held'
  | 'failed-reverted'
  | 'completed'
  | 'rolled-back';

export interface UpdateCandidate {
  id: string;
  channel?: string | null;
  createdAt?: string | null;
  gitCommit?: string | null;
  versions?: ReleaseVersions | null;
  /** Go encodes a nil Reasons slice as null (the tag has no omitempty). */
  risk?: { level: 'patch' | 'minor' | 'major' | 'blocked'; reasons?: string[] | null } | null;
  diff?: { component: string; from: string; to: string }[] | null;
  issues?: string[] | null;
  /** `apply` is omitted by the host CLI (Go omitempty) when it has no apply command to offer. */
  hostCommands?: { plan: string; apply?: string | null } | null;
}

/** Host-measured, sanitized storage totals (no volume or mount names). */
export interface UpdateStorage {
  profileBytes?: number | null;
  keyringBytes?: number | null;
  downloadsBytes?: number | null;
  gatewayDbBytes?: number | null;
  artifactsBytes?: number | null;
  privateBytes?: number | null;
  otherBytes?: number | null;
  totalBytes?: number | null;
}

export interface UpdateStatus {
  phase: UpdatePhase;
  storage?: UpdateStorage | null;
  lastBackupAt?: string | null;
  lastVerifiedAt?: string | null;
  candidates?: UpdateCandidate[] | null;
  pendingPlan?: {
    id: string;
    release: string;
    workspace: string;
    createdAt: string;
    expiresAt: string;
    /** Go omitempty: omitted when empty. */
    blockers?: string[] | null;
    warnings?: string[] | null;
  } | null;
  backup?: {
    count: number;
    retain: number;
    totalBytes: number;
    freeBytes?: number | null;
    lastCheckpoint?: {
      id: string;
      createdAt: string;
      consistency: 'clean' | 'crash';
      releaseId: string;
      /** A nil Go slice without omitempty is encoded as null. */
      datasets?: { role: string; bytes: number }[] | null;
    } | null;
  } | null;
  rollback?: {
    available: boolean;
    checkpointId?: string | null;
    checkpointCreatedAt?: string | null;
    targetRelease?: string | null;
    reason?: string | null;
    dataLossNote?: string;
    unaffected?: string[];
    hostCommand?: string;
  } | null;
  lastOperation?: {
    kind: 'update' | 'rollback';
    id: string;
    status: string;
    startedAt: string;
    finishedAt?: string | null;
    release?: string | null;
    error?: string | null;
  } | null;
}

