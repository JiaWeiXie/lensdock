package storage

import (
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"time"
)

// Errors returned by the object stores.
var (
	// ErrNotFound reports a missing object.
	ErrNotFound = errors.New("storage: object not found")
	// ErrExists reports an artifact directory that already exists.
	ErrExists = errors.New("storage: object already exists")
	// ErrInvalidName reports a key or file name outside the allowed alphabet.
	ErrInvalidName = errors.New("storage: invalid object name")
	// ErrTooLarge reports an object above the read limit.
	ErrTooLarge = errors.New("storage: object too large")
)

var (
	keyPattern  = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,127}$`)
	namePattern = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]{0,63}$`)
)

func validKey(k string) bool { return keyPattern.MatchString(k) }

func validFileName(n string) bool {
	return namePattern.MatchString(n) && !strings.Contains(n, "..")
}

// NewObjectKey returns a random private object key.
func NewObjectKey() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return "obj-" + hex.EncodeToString(b[:]), nil
}

func ensureDir(dir string) error {
	if dir == "" {
		return errors.New("storage: empty directory")
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("storage: create %s: %w", dir, err)
	}
	return nil
}

func syncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer d.Close()
	return d.Sync()
}

// writeFileAtomic writes data to dir/name through a temporary file in dir,
// fsyncs, and renames. perm applies to the final file.
func writeFileAtomic(dir, name string, data []byte, perm os.FileMode) error {
	tmp, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	ok := false
	defer func() {
		if !ok {
			_ = tmp.Close()
			_ = os.Remove(tmpName)
		}
	}()
	if _, err := tmp.Write(data); err != nil {
		return err
	}
	if err := tmp.Chmod(perm); err != nil {
		return err
	}
	if err := tmp.Sync(); err != nil {
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, filepath.Join(dir, name)); err != nil {
		return err
	}
	ok = true
	return syncDir(dir)
}

// Objects is a flat private object directory. Keys are generated by the
// server; they never come from a request.
type Objects struct {
	dir string
}

// OpenObjects creates dir (mode 0700) and returns the store.
func OpenObjects(dir string) (*Objects, error) {
	if err := ensureDir(dir); err != nil {
		return nil, err
	}
	return &Objects{dir: dir}, nil
}

// Put stores data under key atomically and returns its SHA-256 (hex).
func (o *Objects) Put(key string, data []byte) (string, error) {
	if !validKey(key) {
		return "", ErrInvalidName
	}
	if err := writeFileAtomic(o.dir, key, data, 0o600); err != nil {
		return "", fmt.Errorf("storage: write object: %w", err)
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:]), nil
}

// Read returns the object, refusing anything above max bytes (max <= 0 means
// no size cap) or that is not a regular file.
func (o *Objects) Read(key string, max int64) ([]byte, error) {
	if !validKey(key) {
		return nil, ErrInvalidName
	}
	return readRegular(filepath.Join(o.dir, key), max)
}

// Delete removes the object; a missing object is not an error.
func (o *Objects) Delete(key string) error {
	if !validKey(key) {
		return ErrInvalidName
	}
	err := os.Remove(filepath.Join(o.dir, key))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// ObjectInfo describes one stored object.
type ObjectInfo struct {
	Key     string
	ModTime time.Time
}

// List returns the stored objects, ignoring temporary files.
func (o *Objects) List() ([]ObjectInfo, error) {
	ents, err := os.ReadDir(o.dir)
	if err != nil {
		return nil, err
	}
	var out []ObjectInfo
	for _, e := range ents {
		if !e.Type().IsRegular() || !validKey(e.Name()) {
			continue
		}
		info, err := e.Info()
		if err != nil {
			continue
		}
		out = append(out, ObjectInfo{Key: e.Name(), ModTime: info.ModTime()})
	}
	return out, nil
}

func readRegular(path string, max int64) ([]byte, error) {
	if max <= 0 {
		return readRegularUncapped(path)
	}
	st, err := os.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	if !st.Mode().IsRegular() {
		return nil, ErrNotFound
	}
	if st.Size() > max {
		return nil, ErrTooLarge
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, max+1))
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > max {
		return nil, ErrTooLarge
	}
	return data, nil
}

// readRegularUncapped reads a regular, non-symlink file of any size.
func readRegularUncapped(path string) ([]byte, error) {
	st, err := os.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	if !st.Mode().IsRegular() {
		return nil, ErrNotFound
	}
	return os.ReadFile(path)
}

// File is one immutable artifact file.
type File struct {
	Name string
	Data []byte
}

// Artifacts stores immutable published bundles at <root>/<feedbackId>/r<N>/.
type Artifacts struct {
	root string
}

// OpenArtifacts creates root (mode 0700) and returns the store.
func OpenArtifacts(root string) (*Artifacts, error) {
	if err := ensureDir(root); err != nil {
		return nil, err
	}
	return &Artifacts{root: root}, nil
}

func (a *Artifacts) revDir(feedbackID string, revision int) (parent, dir string, err error) {
	if !validKey(feedbackID) || revision < 1 {
		return "", "", ErrInvalidName
	}
	parent = filepath.Join(a.root, feedbackID)
	return parent, filepath.Join(parent, "r"+strconv.Itoa(revision)), nil
}

// Publish writes files into a staging directory, fsyncs them read-only and
// renames the directory into place. It fails with ErrExists when the revision
// directory exists, so a published revision is never overwritten.
func (a *Artifacts) Publish(feedbackID string, revision int, files []File) error {
	parent, dir, err := a.revDir(feedbackID, revision)
	if err != nil {
		return err
	}
	seen := map[string]bool{}
	for _, f := range files {
		if !validFileName(f.Name) || seen[f.Name] {
			return ErrInvalidName
		}
		seen[f.Name] = true
	}
	if err := os.MkdirAll(parent, 0o700); err != nil {
		return err
	}
	if _, err := os.Lstat(dir); err == nil {
		return ErrExists
	}
	var rnd [8]byte
	if _, err := rand.Read(rnd[:]); err != nil {
		return err
	}
	stage := filepath.Join(parent, ".staging-r"+strconv.Itoa(revision)+"-"+hex.EncodeToString(rnd[:]))
	if err := os.Mkdir(stage, 0o700); err != nil {
		return err
	}
	ok := false
	defer func() {
		if !ok {
			_ = os.RemoveAll(stage)
		}
	}()
	for _, f := range files {
		if err := writeFileAtomic(stage, f.Name, f.Data, 0o400); err != nil {
			return fmt.Errorf("storage: write artifact: %w", err)
		}
	}
	if err := os.Rename(stage, dir); err != nil {
		if _, serr := os.Lstat(dir); serr == nil {
			return ErrExists
		}
		return err
	}
	ok = true
	return syncDir(parent)
}

// Read returns one artifact file, refusing symlinks and files above max
// (max <= 0 means no size cap).
func (a *Artifacts) Read(feedbackID string, revision int, name string, max int64) ([]byte, error) {
	_, dir, err := a.revDir(feedbackID, revision)
	if err != nil || !validFileName(name) {
		return nil, ErrInvalidName
	}
	return readRegular(filepath.Join(dir, name), max)
}

// Remove deletes a revision directory (used only to discard an unreferenced
// publish attempt).
func (a *Artifacts) Remove(feedbackID string, revision int) error {
	_, dir, err := a.revDir(feedbackID, revision)
	if err != nil {
		return err
	}
	return os.RemoveAll(dir)
}

// ArtifactDir describes one directory found by List.
type ArtifactDir struct {
	FeedbackID string
	Revision   int // 0 for a staging directory
	Staging    bool
	Path       string
	ModTime    time.Time
}

// List returns every revision and staging directory, for reconciliation.
func (a *Artifacts) List() ([]ArtifactDir, error) {
	fbs, err := os.ReadDir(a.root)
	if err != nil {
		return nil, err
	}
	var out []ArtifactDir
	for _, fb := range fbs {
		if !fb.IsDir() || !validKey(fb.Name()) {
			continue
		}
		revs, err := os.ReadDir(filepath.Join(a.root, fb.Name()))
		if err != nil {
			continue
		}
		for _, r := range revs {
			if !r.IsDir() {
				continue
			}
			info, err := r.Info()
			if err != nil {
				continue
			}
			d := ArtifactDir{FeedbackID: fb.Name(), Path: filepath.Join(a.root, fb.Name(), r.Name()), ModTime: info.ModTime()}
			switch {
			case strings.HasPrefix(r.Name(), ".staging-"):
				d.Staging = true
			case strings.HasPrefix(r.Name(), "r"):
				n, err := strconv.Atoi(r.Name()[1:])
				if err != nil || n < 1 {
					continue
				}
				d.Revision = n
			default:
				continue
			}
			out = append(out, d)
		}
	}
	return out, nil
}

// RemovePath deletes a directory previously returned by List.
func (a *Artifacts) RemovePath(d ArtifactDir) error {
	if !strings.HasPrefix(filepath.Clean(d.Path), filepath.Clean(a.root)+string(filepath.Separator)) {
		return ErrInvalidName
	}
	return os.RemoveAll(d.Path)
}
