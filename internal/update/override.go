package update

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// yamlQuote renders s as a double quoted YAML scalar. Only printable ASCII is
// accepted: every value the update logic emits (image references, Docker
// volume names, hex digests) is validated well before it gets here, so a
// failure means a bug or hostile input, never a formatting detail.
func yamlQuote(s string) (string, error) {
	for _, r := range s {
		if r < 0x20 || r > 0x7e {
			return "", fmt.Errorf("value %q is not printable ASCII", s)
		}
	}
	return strconv.Quote(s), nil
}

type yamlBuilder struct {
	b   strings.Builder
	err error
}

func (y *yamlBuilder) line(indent int, format string, args ...any) {
	y.b.WriteString(strings.Repeat("  ", indent))
	fmt.Fprintf(&y.b, format, args...)
	y.b.WriteByte('\n')
}

func (y *yamlBuilder) quoted(s string) string {
	q, err := yamlQuote(s)
	if err != nil && y.err == nil {
		y.err = err
	}
	return q
}

const overrideHeader = "# Generated by `lensdock update`. Do not edit: it is rewritten on every switch and rollback.\n" +
	"# It pins image digests and maps compose volume keys to the Docker volumes of the current generation.\n"

// RenderGenerationOverride renders the compose override of a generation: for
// every tracked component its image pin and, for every volume key, the exact
// Docker volume (external, so compose never creates or deletes it).
func RenderGenerationOverride(s State) ([]byte, error) {
	y := &yamlBuilder{}
	y.b.WriteString(overrideHeader)
	y.line(0, "# generation %d", s.Generation)
	services := map[string]string{}
	volumes := map[string]string{}
	for _, id := range sortedKeys(s.Components) {
		c := s.Components[id]
		if err := checkDockerName("service", c.Service); err != nil {
			return nil, err
		}
		if err := checkImageRef(c.Image); err != nil {
			return nil, err
		}
		services[c.Service] = c.Image
		for k, v := range c.Volumes {
			if err := checkDockerName("volume key", k); err != nil {
				return nil, err
			}
			if err := checkDockerName("volume", v); err != nil {
				return nil, err
			}
			volumes[k] = v
		}
	}
	y.line(0, "services:")
	for _, svc := range sortedKeys(services) {
		y.line(1, "%s:", svc)
		y.line(2, "image: %s", y.quoted(services[svc]))
	}
	y.line(0, "volumes:")
	for _, k := range sortedKeys(volumes) {
		y.line(1, "%s:", k)
		y.line(2, "name: %s", y.quoted(volumes[k]))
		y.line(2, "external: true")
	}
	if y.err != nil {
		return nil, y.err
	}
	return []byte(y.b.String()), nil
}

// CandidateOverride describes the compose override of the isolated candidate
// project: the candidate runtime on cloned (and scratch or read-only shared)
// volumes, no published ports, no container name, its own operator token and
// no TLS, on an internal network without any route to the outside.
type CandidateOverride struct {
	Service string
	Image   string
	// TokenDigestHex is SHA-256 of the candidate's own operator token.
	TokenDigestHex string
	// Volumes maps compose volume keys to Docker volumes.
	Volumes map[string]string
	// BlankEnv are environment variables forced to the empty string (the
	// runtime TLS settings: candidates speak plain HTTP inside their own
	// network namespace).
	BlankEnv []string
}

// RuntimeTLSEnv includes the mTLS listener and its dependent client-name policy.
var RuntimeTLSEnv = []string{"LENSDOCK_TLS_CERT_FILE", "LENSDOCK_TLS_KEY_FILE", "LENSDOCK_TLS_CLIENT_CA_FILE", "LENSDOCK_TLS_CLIENT_NAMES"}

// RenderCandidateOverride renders the override of a candidate project.
func RenderCandidateOverride(o CandidateOverride) ([]byte, error) {
	if err := checkDockerName("service", o.Service); err != nil {
		return nil, err
	}
	if err := checkImageRef(o.Image); err != nil {
		return nil, err
	}
	if !hex64Pattern.MatchString(o.TokenDigestHex) {
		return nil, fmt.Errorf("candidate token digest must be 64 hex characters")
	}
	y := &yamlBuilder{}
	y.b.WriteString("# Generated by `lensdock update` for an isolated candidate verification.\n")
	y.line(0, "services:")
	y.line(1, "%s:", o.Service)
	y.line(2, "image: %s", y.quoted(o.Image))
	y.line(2, "container_name: !reset null")
	y.line(2, "ports: !reset []")
	y.line(2, "networks: !override")
	y.line(3, "- default")
	y.line(2, "environment:")
	y.line(3, "LENSDOCK_OPERATOR_TOKEN_SHA256: %s", y.quoted(o.TokenDigestHex))
	// The candidate has a scratch policy volume; production policy is retained
	// separately. Its fixture checks exercise CDP even for NOVNC deployments.
	y.line(3, "LENSDOCK_MODE: AGENT")
	blank := append([]string{}, o.BlankEnv...)
	sort.Strings(blank)
	for _, name := range blank {
		if err := checkDockerName("environment variable", name); err != nil {
			return nil, err
		}
		y.line(3, "%s: \"\"", name)
	}
	y.line(0, "volumes:")
	for _, k := range sortedKeys(o.Volumes) {
		if err := checkDockerName("volume key", k); err != nil {
			return nil, err
		}
		if err := checkDockerName("volume", o.Volumes[k]); err != nil {
			return nil, err
		}
		y.line(1, "%s:", k)
		y.line(2, "name: %s", y.quoted(o.Volumes[k]))
		y.line(2, "external: true")
	}
	y.line(0, "networks:")
	y.line(1, "default:")
	y.line(2, "internal: true")
	if y.err != nil {
		return nil, y.err
	}
	return []byte(y.b.String()), nil
}
